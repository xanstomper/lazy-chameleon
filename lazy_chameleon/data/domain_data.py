def get_domain_tasks(domain: str) -> List[Dict]:
    """Return all tasks for a given domain."""
    return DOMAIN_TASK_BANKS.get(domain, [])


def get_random_task(domain: Optional[str] = None) -> Dict:
    """Return a random task from a domain or all tasks."""
    if domain:
        tasks = get_domain_tasks(domain)
    else:
        tasks = [t for ts in DOMAIN_TASK_BANKS.values() for t in ts]
    return random.choice(tasks) if tasks else {"id": "none", "prompt": "No tasks available"}


def get_tasks_by_skill(skill: str) -> List[Dict]:
    """Return all math tasks requiring a specific skill."""
    return [t for t in DOMAIN_TASK_BANKS.get("math", []) if skill in t.get("skills", [])]


